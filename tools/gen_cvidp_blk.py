# Generates the pair and byte loops of the assembler players: cvidh_blk.s and
# cvidp_blk000.s (68000 and 020/030 player), cvxg8_blk.s, cvxd6_blk.s and
# cvxd8_blk.s (020+ rework) - the byte accesses per variant are spelled out
# instead of typed by hand.
#
# Call (from any directory):  python3 tools/gen_cvidp_blk.py
# Changes to the block loops belong HERE, not in the .s file.
#
# Three parts: the direct routines (into the planes themselves), the same ones
# with a change map (suffix m, for shadow planes in fast RAM) and the copy
# routine that brings what changed into chip RAM.
import os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
P, RB, BPL = 5, 40, 10240
BASEK = 2               # plane a2 points at (GRAY with 8 planes: 3)
def D(k, r):            # plane k, row r, relative to plane BASEK / row 0
    return (k - BASEK) * BPL + r * RB
def G(g, k):            # byte k of group g of an entry
    return g * P + k
ORDER = [(r, k) for r in range(4) for k in range(P)]    # i = r*P + k
def setp(n):            # number of planes of the routines below (5 PLANAR, 4 HAM6)
    global P, ORDER
    P = n
    ORDER = [(r, k) for r in range(4) for k in range(P)]
LEFT4  = {0: (0, 1, 'd1', 'd2'), 1: (4, 5, 'd1', 'd2'), 2: (0, 1, 'd3', 'd4'), 3: (4, 5, 'd3', 'd4')}
RIGHT4 = {0: (2, 3, 'd1', 'd2'), 1: (6, 7, 'd1', 'd2'), 2: (2, 3, 'd3', 'd4'), 3: (6, 7, 'd3', 'd4')}
DIRTY = 3 * BPL         # Aenderungskarte: sechste "Plane", relativ zu Plane 2
MK = f'        st      {DIRTY}(a2)                    ; Aenderungskarte'
o = []
def e(s=''): o.append(s)

e('''* cvidp_blk.s - Cinepak blocks straight into 5 bitplanes, for EVERY 68k CPU
*
* GENERATED by tools/gen_cvidp_blk.py - change it there, not here: the 20 byte
* accesses per variant are spelled out. Model and yardstick is the C version in
* src/codec/cvidplanar.c; the planar bench checked both frame by frame against
* chunky + C2P.
*
* Fixed geometry of the ECS path: 320 wide, 40 bytes per row, 5 planes linear
* at a distance of 10240 (320x256). cvidp_decode() calls these routines only
* then, otherwise the C path.
*
* ADDRESSING WITHOUT SCALING: a2 points at plane 2, first row of the block row,
* byte of the current column. All 5 planes x 4 rows therefore lie between
* -20480 and +20600 - 16-bit displacements without an index, which the 68000
* can do. Codebook entries are 64 bytes, so the offset is index << 6, and a
* byte inside one lies at 39 at most: (d8,An,Xn.w).
*
* PAIRS: a block is one nibble per plane and row, two blocks are one byte. The
* left block is only prepared - V1: a3 points at its finished 20-byte image in
* the entry; V4: assembled in the scratch buffer of the state. The right one
* writes both as whole bytes. If one half is missing, its nibble in the target
* is preserved (read, mask, write). At the end of a chunk an open left half is
* written the same way with preservation - so the result is exact even when a
* pair reaches across a chunk boundary.
*
*
* ADDRESS ERROR: the first version read the flag word with move.l (a0)+ - after
* a V1 block a0 sits on an odd address, and the 68000 stood there with guru
* 8000 0003. It is therefore read byte by byte; all other accesses through a0
* are bytes.
*
* SHADOW MODE (suffix m): the same routines, except that every writing place
* also sets `st 30720(a2)` - the byte of the same column in the first row of a
* sixth "plane" right behind the five. That is the change map.
* cvidp_copy_marked_asm at the end of the file then brings only what changed
* into the chip planes: one longword per 4-byte group when both halves changed,
* otherwise the single word. Why: on the A600 every chip bus cycle costs about
* 0.9 us, and half bytes written directly need two of them.
*
*
* Register use
*   a0 from   a1 cend   a2 q (plane 2)   a3 image of the left half
*   a4 V4 codebook      a5 V1 codebook   a6 state (cvidp_asmst)
*   d0 byte   d1-d4 entry offsets (index << 6)
*   d5 flag word   d6 bit counter   d7 blocks to the end of the row (word),
*                                 bit 31 = left half prepared

ST_FROM  equ 0
ST_CEND  equ 4
ST_Q     equ 8
ST_CB0   equ 12
ST_CB1   equ 16
ST_REM   equ 20                              ; ROWS to the end of the strip
ST_COL   equ 24
ST_WRAP  equ 28
ST_ROWS  equ 32
ST_BCOLS equ 36
ST_SCR   equ 40

        section code
''')

# --- gemeinsam: Register laden ---------------------------------------------
e('''* Load the registers from the state (a6 is already set).
cvidp_load:
        movea.l ST_FROM(a6),a0
        movea.l ST_CEND(a6),a1
        movea.l ST_Q(a6),a2
        movea.l ST_CB0(a6),a4
        movea.l ST_CB1(a6),a5
        move.l  ST_COL(a6),d7
        rts''')

def writers(x, mark):
    e(f'''
* Write an open left half, then the state back.
cvidp_finish{x}:
        btst    #0,d7
        beq.s   .store                       ; even: no half is open
        btst    #31,d7
        beq.s   .store
        bsr     cvidp_flush_left{x}
        bclr    #31,d7
.store:
        move.l  a0,ST_FROM(a6)
        move.l  a2,ST_Q(a6)
        move.l  d7,ST_COL(a6)
        rts

* Linke Haelfte allein (rechts uebersprungen): unteres Halbbyte bleibt.
cvidp_flush_left{x}:''')
    if mark: e(MK)
    for (r, k) in ORDER:
        i = r * P + k
        e(f'        move.b  {D(k,r)}(a2),d0')
        e(f'        andi.b  #$0F,d0')
        e(f'        or.b    {i}(a3),d0')
        e(f'        move.b  d0,{D(k,r)}(a2)')
    e('        rts')
    e('')

    # --- V1 ----------------------------------------------------------------
    e('* V1-Block, d1 = Index << 6 im V1-Codebook.')
    e(f'cvidp_emit_v1{x}:')
    e('        btst    #0,d7')
    e('        bne.s   .right')
    e('        lea     0(a5,d1.w),a3                ; finished image of the left position')
    e('        bset    #31,d7')
    e('        rts')
    e('.right:')
    if mark: e(MK)
    e('        btst    #31,d7')
    e('        beq     .pres')
    for (r, k) in ORDER:
        i = r * P + k
        e(f'        move.b  {i}(a3),d0')
        e(f'        or.b    {20+i}(a5,d1.w),d0')
        e(f'        move.b  d0,{D(k,r)}(a2)')
    e('        rts')
    e('.pres:                                       ; links uebersprungen: oberes Halbbyte bleibt')
    for (r, k) in ORDER:
        i = r * P + k
        e(f'        move.b  {D(k,r)}(a2),d0')
        e(f'        andi.b  #$F0,d0')
        e(f'        or.b    {20+i}(a5,d1.w),d0')
        e(f'        move.b  d0,{D(k,r)}(a2)')
    e('        rts')
    e('')

    # --- V4 ----------------------------------------------------------------
    e('* V4-Block, d1-d4 = Indizes << 6 im V4-Codebook.')
    e(f'cvidp_emit_v4{x}:')
    e('        btst    #0,d7')
    e('        bne     .right')
    e('        lea     ST_SCR(a6),a3')
    for (r, k) in ORDER:
        i = r * P + k
        ga, gb, ea, eb = LEFT4[r]
        e(f'        move.b  {G(ga,k)}(a4,{ea}.w),d0')
        e(f'        or.b    {G(gb,k)}(a4,{eb}.w),d0')
        e(f'        move.b  d0,{i}(a3)')
    e('        bset    #31,d7')
    e('        rts')
    e('.right:')
    if mark: e(MK)
    e('        btst    #31,d7')
    e('        beq     .pres')
    for (r, k) in ORDER:
        i = r * P + k
        ga, gb, ea, eb = RIGHT4[r]
        e(f'        move.b  {i}(a3),d0')
        e(f'        or.b    {G(ga,k)}(a4,{ea}.w),d0')
        e(f'        or.b    {G(gb,k)}(a4,{eb}.w),d0')
        e(f'        move.b  d0,{D(k,r)}(a2)')
    e('        rts')
    e('.pres:')
    for (r, k) in ORDER:
        ga, gb, ea, eb = RIGHT4[r]
        e(f'        move.b  {D(k,r)}(a2),d0')
        e(f'        andi.b  #$F0,d0')
        e(f'        or.b    {G(ga,k)}(a4,{ea}.w),d0')
        e(f'        or.b    {G(gb,k)}(a4,{eb}.w),d0')
        e(f'        move.b  d0,{D(k,r)}(a2)')
    e('        rts')
    e('')

ADV = '''        subq.w  #1,d7                        ; Blockvorschub
        beq.s   .wr_%(n)s
        btst    #0,d7
        bne.s   .nx_%(n)s                     ; odd: the left one was due
        addq.l  #1,a2
        bclr    #31,d7
        bra.s   .nx_%(n)s
.wr_%(n)s:
        move.w  ST_BCOLS+2(a6),d7
        bclr    #31,d7
        adda.l  ST_WRAP(a6),a2
        subq.l  #1,ST_REM(a6)                ; one row less - check only here
        beq     .done
.nx_%(n)s:'''
FETCH1 = '''        moveq   #0,d1
        move.b  (a0)+,d1
        lsl.w   #6,d1'''
FETCH4 = '\n'.join(f'''        moveq   #0,{d}
        move.b  (a0)+,{d}
        lsl.w   #6,{d}''' for d in ('d1', 'd2', 'd3', 'd4'))
HAVE4 = '''        move.l  a0,d0
        addq.l  #4,d0
        cmp.l   a1,d0
        bhi     .done'''
FLAG = '''        move.b  (a0)+,d5                     ; flag word BYTE BY BYTE: a0 may be
        lsl.l   #8,d5                        ; odd, and a move.l from there is an
        move.b  (a0)+,d5                     ; address error on the 68000 (guru
        lsl.l   #8,d5                        ; 8000 0003) - as GETFLAG in
        move.b  (a0)+,d5                     ; cvid_blk8_000.s
        lsl.l   #8,d5
        move.b  (a0)+,d5'''

def loops(x):
    e(f'''* -------- 0x3200: V1 only -------------------------------------------------
        xdef    _cvidp_blk3200{x}
_cvidp_blk3200{x}:
        movem.l d2-d7/a2-a6,-(sp)
        movea.l 48(sp),a6
        bsr     cvidp_load
        tst.l   ST_REM(a6)
        beq     .done
.loop:
        cmpa.l  a1,a0
        bcc     .done
{FETCH1}
        bsr     cvidp_emit_v1{x}
{ADV % dict(n='a')}
        bra     .loop
.done:
        bsr     cvidp_finish{x}
        movem.l (sp)+,d2-d7/a2-a6
        rts

* -------- 0x3000: V1/V4, one flag bit per block -------------------------
        xdef    _cvidp_blk3000{x}
_cvidp_blk3000{x}:
        movem.l d2-d7/a2-a6,-(sp)
        movea.l 48(sp),a6
        bsr     cvidp_load
        tst.l   ST_REM(a6)
        beq     .done
.word:
{HAVE4}
{FLAG}
        moveq   #31,d6
.bit:
        add.l   d5,d5
        bcs.s   .v4
        cmpa.l  a1,a0
        bcc     .done
{FETCH1}
        bsr     cvidp_emit_v1{x}
        bra.s   .adv
.v4:
{HAVE4}
{FETCH4}
        bsr     cvidp_emit_v4{x}
.adv:
{ADV % dict(n='b')}
        dbf     d6,.bit
        bra     .word
.done:
        bsr     cvidp_finish{x}
        movem.l (sp)+,d2-d7/a2-a6
        rts

* -------- 0x3100: skip bit, then type bit, across word boundaries ---------
        xdef    _cvidp_blk3100{x}
_cvidp_blk3100{x}:
        movem.l d2-d7/a2-a6,-(sp)
        movea.l 48(sp),a6
        bsr     cvidp_load
        moveq   #0,d6                        ; no bits in the flag word
        tst.l   ST_REM(a6)
        beq     .done
.blk:
        tst.w   d6
        bne.s   .h1
{HAVE4}
{FLAG}
        moveq   #32,d6
.h1:
        subq.w  #1,d6
        add.l   d5,d5
        bcc.s   .skip
        tst.w   d6
        bne.s   .h2
{HAVE4}
{FLAG}
        moveq   #32,d6
.h2:
        subq.w  #1,d6
        add.l   d5,d5
        bcs.s   .v4
        cmpa.l  a1,a0
        bcc     .done
{FETCH1}
        bsr     cvidp_emit_v1{x}
        bra.s   .adv
.v4:
{HAVE4}
{FETCH4}
        bsr     cvidp_emit_v4{x}
        bra.s   .adv
.skip:
        btst    #0,d7                        ; links uebersprungen: nichts zu tun
        beq.s   .adv                         ; (the note is always empty there)
        btst    #31,d7
        beq.s   .adv
        bsr     cvidp_flush_left{x}          ; rechts uebersprungen, links offen
.adv:
{ADV % dict(n='c')}
        bra     .blk
.done:
        bsr     cvidp_finish{x}
        movem.l (sp)+,d2-d7/a2-a6
        rts''')

# --- Direkte Routinen: Paarschleifen ------------------------------------------
#
# The loop works IN PAIRS (two blocks = one plane byte per plane and row).
# Which kind the left half was is no longer held in d7 (bit 31, btst #0 per
# block) but in WHERE the code is running:
#   .L    linke Position, nichts offen
#   .RS   right, left skipped               (writes with preservation, upper nibble)
#   .R1   right, left V1 (a3 = entry)       (V1V1: row 1/3 = row 0/2)
#   .R4   right, left V4 (a3 = buffer)
# The writing instructions live in the pair, without bsr/rts.
#
# Flag bits with a guard bit: d5 holds the bits still open left-aligned, with a
# 1 below them. `add.l d5,d5` delivers the bit in the carry; if d5 is zero
# afterwards, what was shifted out was the guard bit - then reload the flag word
# (byte by byte, as before: a0 may be odd), `add.l` for the first bit and
# `bset #0` sets the new guard bit (bset changes only Z, the carry stays).
# That saves the bit counter d6, the tst.w and the subq.w per bit.
#
# 0x3100 TWO SKIPPED BLOCKS AT ONCE: at the left position d5 < $40000000 means
# that the top two bits are zero - and because the guard bit (a 1) lies below
# all open bits, both are real flag bits. The pair is skipped entirely: two
# bits gone, a2 further on.
#
# Register use (direct routines)
#   a0 from   a1 cend   a2 q (plane 2)   a3 image of the left half
#   a4 V4 codebook      a5 V1 codebook   a6 state (cvidp_asmst)
#   d0 byte   d1-d4 entry offsets (index << 6)   d2 also scratch
#   d5 flag bits with guard bit   d6 $40000000 (0x3000/0x3100)
#   d7 PAIRS to the end of the row (word)
# ST_COL stays "blocks to the end of the row" (2 * d7, on the right 2 * d7 - 1):
# odd means "right, left skipped" at the next chunk.
#
# TWO V1V1 PAIRS AS A WORD: if a V1V1 pair sits at an even byte column (d7
# even) and the next pair is V1V1 as well, both bytes per plane row are written
# as ONE word - one chip bus cycle instead of two. The following bits are looked
# at in advance: 0x3100 `1010` (coded V1, coded V1), 0x3000 `00`, each only when
# the guard bit lies below them, so that all four or two are real flag bits; on
# top of that two index bytes have to be there. Otherwise it carries on pair by
# pair - the same abort points as before. Word addresses are even: planes are
# even (cvidp_decode checks it), the column
# gerade.

# Options of the pair loops. cvidp_blk.s (for 68020 and up) stays without
# options, byte by byte as before. The 68000 player gets all of them, each one
# measured in the time model and checked against the plane dumps:
#   bits  bit 0 without a reload check: the guard only falls with carry = 1
#   v4d   V4 left without the 20-byte scratch buffer, mixed while writing
#   wrd   word pairs without lsl #8: the lower byte is overwritten, not or-ed
#   a3p   read entries with (a3)+ instead of a displacement
#   sk4   four skipped pairs in one step (0x3100)
#   dbf   pair counter with dbf instead of subq/bne
#   key2  Schnellweg V1V1|V1V1 an gerader Spalte (0x3000, Keyframes)
# GENOPT=a,b,... replaces the list for the 68000 files (GENOPT= : none).
OPT = set()
OPT68K = set(x for x in os.environ.get('GENOPT', 'bits,v4d,wrd,a3p,sk4,dbf,key2').split(',') if x)

def pair_loops(prefix='cvidp'):
    BITS = 'bits' in OPT; V4D = 'v4d' in OPT; WRD = 'wrd' in OPT; KEY = 'key' in OPT or 'key2' in OPT; KEY2 = 'key2' in OPT
    SK4 = 'sk4' in OPT; A3P = 'a3p' in OPT; DBF = 'dbf' in OPT
    NE = 'bpl' if DBF else 'bne'
    def w(s=''): e(s)
    def fetch(d):
        w(f'        moveq   #0,{d}'); w(f'        move.b  (a0)+,{d}'); w(f'        lsl.w   #6,{d}')
    def fetch1(): fetch('d1')
    def fetch4():
        for d in ('d1', 'd2', 'd3', 'd4'): fetch(d)
    def have1(fail): w('        cmpa.l  a1,a0'); w(f'        bcc     {fail}')
    def have4(fail):
        w('        move.l  a0,d0'); w('        addq.l  #4,d0'); w('        cmp.l   a1,d0'); w(f'        bhi     {fail}')
    refills = []
    def bit_cc(tag, fail, target):      # bit 0 -> target, bit 1 falls through
        w('        add.l   d5,d5')
        if BITS:
            w(f'        bcc     {target}'); w(f'        beq     .rf{tag}'); w(f'.c{tag}:')
        else:
            w(f'        beq     .rf{tag}'); w(f'.c{tag}:'); w(f'        bcc     {target}')
        refills.append((tag, fail, 'cc', target))
    def bit_cs(tag, fail, target):      # bit 1 -> target (with entry_cs), bit 0 falls through
        w('        add.l   d5,d5')
        if BITS:
            w(f'        bcs     {target}'); w(f'.c{tag}:')
        else:
            w(f'        beq     .rf{tag}'); w(f'.c{tag}:'); w(f'        bcs     {target}')
        refills.append((tag, fail, 'cs', target))
    def entry_cs(tag, label):
        w(f'{label}:')
        if BITS:
            w(f'        beq     .rf{tag}                     ; guard instead of bit 1'); w(f'{label}c:')
    def emit_refills():
        for tag, fail, mode, target in refills:
            w(f'.rf{tag}:')
            have4(fail)
            w('        move.b  (a0)+,d5                     ; byte by byte: a0 may be odd')
            w('        lsl.l   #8,d5')
            w('        move.b  (a0)+,d5')
            w('        lsl.l   #8,d5')
            w('        move.b  (a0)+,d5')
            w('        lsl.l   #8,d5')
            w('        move.b  (a0)+,d5')
            w('        add.l   d5,d5                        ; first bit into the carry')
            w('        bset    #0,d5                        ; Waechterbit, Carry bleibt')
            if BITS:
                if mode == 'cc': w(f'        bcc     {target}')
                else: w(f'        bcs     {target}c')
            w(f'        bra     .c{tag}')
        refills.clear()
    def gap(): w(f'        addq.l  #{P},a3')
    # --- Schreibbloecke ---------------------------------------------------------
    def write11():
        for r in (0, 2):
            for k in range(P):
                i = r * P + k
                w(f'        move.b  (a3)+,d0' if A3P else f'        move.b  {i}(a3),d0')
                w(f'        or.b    {4*P+i}(a5,d1.w),d0')
                w(f'        move.b  d0,{D(k,r)}(a2)')
                w(f'        move.b  d0,{D(k,r+1)}(a2)')
            if A3P and r == 0: gap()
    def write_double():
        for r in (0, 2):
            for k in range(P):
                i = r * P + k
                if WRD and k % 2 == 0:
                    w(f'        move.w  {i}(a3),d0                  ; even offset: word, lower byte follows')
                    w(f'        or.w    {4*P+i}(a5,d1.w),d0')
                    w(f'        move.b  {i}(a5,d2.w),d0')
                    w(f'        or.b    {4*P+i}(a5,d3.w),d0')
                elif WRD:
                    w(f'        move.b  {i}(a3),d0')
                    w(f'        or.b    {4*P+i}(a5,d1.w),d0')
                    w('        move.b  d0,-(sp)                     ; upper byte without lsl #8')
                    w('        move.w  (sp)+,d0')
                    w(f'        move.b  {i}(a5,d2.w),d0')
                    w(f'        or.b    {4*P+i}(a5,d3.w),d0')
                else:
                    w(f'        move.b  {i}(a3),d0')
                    w(f'        or.b    {4*P+i}(a5,d1.w),d0')
                    w('        lsl.w   #8,d0')
                    w(f'        or.b    {i}(a5,d2.w),d0')
                    w(f'        or.b    {4*P+i}(a5,d3.w),d0')
                w(f'        move.w  d0,{D(k,r)}(a2)')
                w(f'        move.w  d0,{D(k,r+1)}(a2)')
    def write_r1_after4():
        if V4D:     # d1-d4 left V4 indices, a3 -> right V1 entry row 0
            for r in (0, 2):
                for k in range(P):
                    for rr in (r, r + 1):
                        ga, gb, ea, eb = LEFT4[rr]
                        w(f'        move.b  {G(ga,k)}(a4,{ea}.w),d0')
                        w(f'        or.b    {G(gb,k)}(a4,{eb}.w),d0')
                        w('        or.b    (a3),d0' if rr == r else '        or.b    (a3)+,d0')
                        w(f'        move.b  d0,{D(k,rr)}(a2)')
                if r == 0: gap()
            return
        for r in (0, 2):
            for k in range(P):
                i = r * P + k
                w(f'        move.b  {4*P+i}(a5,d1.w),d2')
                for rr in (r, r + 1):
                    w(f'        move.b  {rr*P+k}(a3),d0')
                    w('        or.b    d2,d0')
                    w(f'        move.b  d0,{D(k,rr)}(a2)')
    def write_r4():
        for (r, k) in ORDER:
            i = r * P + k
            ga, gb, ea, eb = RIGHT4[r]
            w('        move.b  (a3)+,d0' if A3P else f'        move.b  {i}(a3),d0')
            w(f'        or.b    {G(ga,k)}(a4,{ea}.w),d0')
            w(f'        or.b    {G(gb,k)}(a4,{eb}.w),d0')
