# --- DHAM6 and DHAM8: double width, a block is a whole byte -------------------
#
# Source column x occupies the screen columns 2x and 2x+1, and the pattern per
# screen column mod 4 is blue, green, red, green. A 4x4 block is 8 screen
# pixels, so exactly one byte per plane and row: no nibbles, no pairs, and a
# skipped block touches nothing. 80 bytes per row, plane 20480 bytes.
#
# Entries (64 bytes in size, the first 4 * GS are used), byte k of a group =
# data plane k, GS = 4 (DHAM6) or 8 (DHAM8):
#   V1  group 0 rows 0/1: B(y0) G(y0) R(y0) G(y0) B(y1) G(y1) R(y1) G(y1)
#       group 1 rows 2/3: the same with y2 y3
#   V4  group 0 = top << 4, group 1 = top, group 2 = bottom << 4,
#       group 3 = bottom; top = B(y0) G(y0) R(y1) G(y1), bottom with y2 y3
#   Row 0 = G0(a) | G1(b), row 1 = G2(a) | G3(b), rows 2/3 with c, d.
#
# Addressing: a2 points at plane 1 (planes 0-2), a3 at plane KB2 (the rest) -
# each +-20480 plus the row, 16 bit.
#
# Register use
#   a0 from   a1 cend   a2 plane 1   a3 plane KB2   a4 V4 codebook
#   a5 V1 codebook      a6 state (cvidp_asmst, ST_Q = a2)
#   d0 byte   d1-d4 entry offsets (index << 6)   d5 flag bits with guard bit
#   d7 blocks to the end of the row (word)
def byte_loops(prefix, PD, GS, KB2):
    RBb, BPLb, BCOLS = 80, 20480, 80
    dist = (KB2 - 1) * BPLb
    def w(s=''): e(s)
    def adr(k, r):
        if k < 3:
            return '%d(a2)' % ((k - 1) * BPLb + r * RBb)
        return '%d(a3)' % ((k - KB2) * BPLb + r * RBb)
    def fetch(d):
        w(f'        moveq   #0,{d}'); w(f'        move.b  (a0)+,{d}'); w(f'        lsl.w   #6,{d}')
    def emit_v1():
        for k in range(PD):
            w(f'        move.b  {k}(a5,d1.w),d0')
            w(f'        move.b  d0,{adr(k,0)}')
            w(f'        move.b  d0,{adr(k,1)}')
            w(f'        move.b  {GS+k}(a5,d1.w),d0')
            w(f'        move.b  d0,{adr(k,2)}')
            w(f'        move.b  d0,{adr(k,3)}')
    def emit_v4():
        for k in range(PD):
            for r, (ea, eb, ga, gb) in enumerate((('d1', 'd2', 0, 1), ('d1', 'd2', 2, 3),
                                                 ('d3', 'd4', 0, 1), ('d3', 'd4', 2, 3))):
                w(f'        move.b  {ga*GS+k}(a4,{ea}.w),d0')
                w(f'        or.b    {gb*GS+k}(a4,{eb}.w),d0')
                w(f'        move.b  d0,{adr(k,r)}')
    def have4(fail):
        w('        move.l  a0,d0'); w('        addq.l  #4,d0'); w('        cmp.l   a1,d0'); w(f'        bhi     {fail}')
    refills = []
    def bit(tag):                       # Bit ins Carry, Waechter nachladen
        w('        add.l   d5,d5')
        w(f'        beq     .rf{tag}')
        w(f'.c{tag}:')
        refills.append(tag)
    def routine(kind):
        name = f'_{prefix}_blk{kind:04x}'
        w(f'* -------- 0x{kind:04x} ' + '-' * 60)
        w(f'        xdef    {name}')
        w(f'{name}:')
        w('        movem.l d2-d7/a2-a6,-(sp)')
        w('        movea.l 48(sp),a6')
        w('        tst.l   ST_REM(a6)')
        w('        beq     .exit')
        w('        movea.l ST_FROM(a6),a0')
        w('        movea.l ST_CEND(a6),a1')
        w('        movea.l ST_Q(a6),a2')
        w('        movea.l a2,a3')
        w(f'        adda.l  #{dist},a3')
        w('        movea.l ST_CB0(a6),a4')
        w('        movea.l ST_CB1(a6),a5')
        w('        move.l  #$80000000,d5                ; only the guard bit')
        w('        move.l  ST_COL(a6),d7                ; blocks to the end of the row')
        w('.blk:')
        if kind == 0x3100:
            bit('0'); w('        bcc     .adv                         ; uebersprungen')
        if kind != 0x3200:
            bit('1'); w('        bcs     .v4')
        w('        cmpa.l  a1,a0')
        w('        bcc     .done')
        fetch('d1')
        emit_v1()
        if kind != 0x3200:
            w('        bra     .adv')
            w('.v4:')
            have4('.done')
            for d in ('d1', 'd2', 'd3', 'd4'): fetch(d)
            emit_v4()
        w('.adv:')
        w('        addq.l  #1,a2')
        w('        addq.l  #1,a3')
        w('        subq.w  #1,d7')
        w('        bne     .blk')
        w(f'        lea     {3*RBb}(a2),a2               ; next block row')
        w(f'        lea     {3*RBb}(a3),a3')
        w(f'        moveq   #{BCOLS},d7')
        w('        subq.l  #1,ST_REM(a6)')
        w('        bne     .blk')
        w('.done:')
        w('        move.l  a0,ST_FROM(a6)')
        w('        move.l  a2,ST_Q(a6)')
        w('        move.l  d7,ST_COL(a6)')
        w('.exit:')
        w('        movem.l (sp)+,d2-d7/a2-a6')
        w('        rts')
        for tag in refills:
            w(f'.rf{tag}:')
            have4('.done')
            w('        move.l  (a0)+,d5                     ; 68020 and up: also at an odd address')
            w('        add.l   d5,d5                        ; erstes Bit ins Carry')
            w('        bset    #0,d5                        ; Waechterbit, Carry bleibt')
            w(f'        bra     .c{tag}')
        refills.clear()
        w('')
    routine(0x3200)
    routine(0x3000)
    routine(0x3100)

